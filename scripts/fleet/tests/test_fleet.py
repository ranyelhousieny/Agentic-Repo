def test_api_errors_leave_the_previous_cache_intact(tmp_path):
    """The module docstring promises a non-404 error 'leaves any previous cache
    intact'. Deleting 404'd files inline broke that: a run whose first artifacts were
    absent and whose rest errored unlinked cached files, then returned UNVERIFIED
    without rewriting _meta.json -- metadata saying `ok` beside files that were gone."""
    from fetch_member_artifacts import fetch_member

    member = {"slug": "m1", "gitlab_path": "g/m1", "default_branch": "main"}
    cache = str(tmp_path / "cache")

    def head_fn(gp, branch):
        return "sha1", "2026-08-15", None

    def raw_ok(gp, rel, ref):
        return "# %s\n" % rel, "ok"

    assert fetch_member(member, cache, head_fn=head_fn, raw_fn=raw_ok)["status"] == "fetched"
    cached = os.path.join(cache, "m1", "CLAUDE.md")
    assert os.path.isfile(cached)

    # next run: CLAUDE.md now 404s, everything after it errors -> nothing fetched
    def raw_absent_then_error(gp, rel, ref):
        return (None, "absent") if rel == "CLAUDE.md" else (None, "error")

    r = fetch_member(member, cache, force=True,
                     head_fn=head_fn, raw_fn=raw_absent_then_error)
    assert r["status"] == "UNVERIFIED"
    assert os.path.isfile(cached), "an UNVERIFIED run must not mutate the cache"
    meta = json.load(open(os.path.join(cache, "m1", "_meta.json")))
    assert meta["files"]["CLAUDE.md"] == "ok", "metadata must still describe what is on disk"

    # a run that DOES fetch still prunes an upstream-deleted artifact
    def raw_absent_then_ok(gp, rel, ref):
        return (None, "absent") if rel == "CLAUDE.md" else ("# %s\n" % rel, "ok")

    r = fetch_member(member, cache, force=True,
                     head_fn=head_fn, raw_fn=raw_absent_then_ok)
    assert r["status"] == "fetched"
    assert not os.path.isfile(cached), "an artifact deleted upstream must leave the cache"


