def test_group_projects_pagination_and_dedup():
    pages = {
        1: [{"id": i} for i in range(100)],
        2: [{"id": 99}, {"id": 100}],   # overlap on 99 must dedup
    }

    def fetch(path):
        import re as _re
        page = int(_re.search(r"&page=(\d+)", path).group(1))
        return pages.get(page, [])

    got = group_projects("example%2Fgroup", fetch=fetch)
    assert len(got) == 101
    assert len({p["id"] for p in got}) == 101


