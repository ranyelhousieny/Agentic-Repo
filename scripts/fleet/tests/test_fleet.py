def test_cache_blind_columns_are_not_reported_as_absent(project):
    """`readiness` and `graph edges` come from artifacts the converter git-ignores in
    the target repo, so a default-branch replica structurally cannot carry them.
    Rendering them as `--` next to genuinely-absent artifacts read as "this repo has
    none" -- and the Maestro lane makes cache the primary source, so that was most rows."""
    make_cache_member(project, "mini-c")
    assert run_script("build_fleet_registry.py", "--project-dir", str(project)).returncode == 0
    md = open(project / "Generated" / "FLEET_REGISTRY.md").read()
    row = [l for l in md.splitlines() if l.startswith("| mini-c |")][0]
    assert "| cache |" in row and "n/a*" in row
    assert "| mini-a |" in md and "n/a*" not in [l for l in md.splitlines()
                                                 if l.startswith("| mini-a |")][0]
    assert "this SOURCE cannot see it" in md          # the legend explains the cell

    # the router must make the same distinction -- it renders the same measurement
    assert run_script("build_project_index.py", "--project-dir", str(project)).returncode == 0
    idx = open(project / "PROJECT_INDEX.md").read()
    c_line = [l for l in idx.splitlines() if l.startswith("- **mini-c**")][0]
    assert "[n/a*]" in c_line, "a cache row's readiness is unmeasurable, not absent"
    a_line = [l for l in idx.splitlines() if l.startswith("- **mini-a**")][0]
    assert "[L2]" in a_line                            # local clone still reports its level
    assert "this source cannot see it" in idx          # legend carries the distinction


