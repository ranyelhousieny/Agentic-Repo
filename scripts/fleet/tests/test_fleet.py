    # the regex backtracks over the newline and captures `dev_classification: Growth`,
    # so an empty value reads as filled everywhere except the end of the file -- which
    # is the one position a careless fixture puts it in.
    p.write_text("jira_project: TST\nepic: TODO\nboard:\ndev_classification: Growth\n")
    todo, missing = binding_gaps(str(p))
    assert set(todo) == {"epic", "board"}                       # empty value == unfilled
    assert set(missing) == {"assignee_account_id"}

    # every ordering of the empty field: first, middle, last
    for text, expect_empty in (
        ("epic:\njira_project: TST\nboard: 42\n"
         "dev_classification: Growth\nassignee_account_id: a\n", "epic"),
        ("jira_project: TST\nepic: TST-1\nboard:\n"
         "dev_classification: Growth\nassignee_account_id: a\n", "board"),
        ("jira_project: TST\nepic: TST-1\nboard: 42\n"
         "dev_classification: Growth\nassignee_account_id:\n", "assignee_account_id"),
    ):
        q = tmp_path / "b2.yml"
        q.write_text(text)
        todo, missing = binding_gaps(str(q))
        assert todo == [expect_empty], (text, todo, missing)
        assert missing == []
    p.write_text(COMPLETE_BINDING)
    assert binding_gaps(str(p)) == ([], [])
    assert binding_gaps(str(tmp_path / "nope.yml")) == ([], list(
        __import__("project_verify").BINDING_FIELDS))


