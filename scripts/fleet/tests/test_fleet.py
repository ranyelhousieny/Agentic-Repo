def test_catalog_info_is_read_as_text_not_json():
    """The `/raw` file endpoint returns the file's bytes. Routing catalog-info.yaml
    through the JSON decoder returned None for every repo, so `role` and
    `owning_manager` were permanently empty while the agent prompt told a human to
    build the Phase 2 policy table and Phase 5 TEAM.md out of them."""
    raw = ("apiVersion: backstage.io/v1alpha1\nkind: Component\n"
           "metadata:\n  name: svc\nspec:\n  type: service\n"
           "  owningManager: someone@example.com\n")
    assert catalog_fields(raw) == ("service", "someone@example.com")
    # the regression, pinned: the JSON path cannot represent this file at all
    with pytest.raises(ValueError):
        json.loads(raw)
    assert catalog_fields("") == ("", "")
    assert catalog_fields("kind: Component\n") == ("", "")
    # a nested lookalike key must not answer for spec.type
    assert catalog_fields("spec:\n  mediaType: application/json\n")[0] == ""
    assert glab is not None  # imported to document that the JSON decoder still exists
