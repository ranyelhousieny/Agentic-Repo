def test_fetch_member_with_stubs(tmp_path):
    from fetch_member_artifacts import fetch_member

    content = {
        "CLAUDE.md": "# CLAUDE\n",
        "Knowledge/KNOWLEDGE_GRAPH.md": "# KG\n**Last Updated:** 2026-08-15\n",
    }
    calls = {"head": 0, "raw": 0}

    def head_fn(gp, branch):
        calls["head"] += 1
        return "sha1234567", "2026-08-15", None

    def raw_fn(gp, rel, ref):
        calls["raw"] += 1
        assert ref == "sha1234567"                 # fetch pinned to the head SHA
        if rel in content:
            return content[rel], "ok"
        return None, "absent"

    member = {"slug": "m1", "gitlab_path": "g/m1", "default_branch": "main"}
    cache = str(tmp_path / "cache")
    r = fetch_member(member, cache, head_fn=head_fn, raw_fn=raw_fn)
    assert r["status"] == "fetched" and r["ok"] == 2 and r["errors"] == 0
    meta = json.load(open(os.path.join(cache, "m1", "_meta.json")))
    assert meta["sha"] == "sha1234567"
    assert meta["files"]["CLAUDE.md"] == "ok"
    assert meta["files"]["AGENTS.md"] == "absent"  # absence recorded, not guessed
    assert open(os.path.join(cache, "m1", "CLAUDE.md")).read() == "# CLAUDE\n"

    # unchanged SHA -> skipped without any raw fetches
    before = calls["raw"]
    r2 = fetch_member(member, cache, head_fn=head_fn, raw_fn=raw_fn)
    assert r2["status"] == "current" and calls["raw"] == before

    # head error -> UNVERIFIED, cache untouched
    def head_err(gp, branch):
        return None, None, "500 boom"
    r3 = fetch_member(member, cache, head_fn=head_err, raw_fn=raw_fn)
    assert r3["status"] == "UNVERIFIED"
    assert os.path.isfile(os.path.join(cache, "m1", "CLAUDE.md"))


